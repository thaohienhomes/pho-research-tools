#!/usr/bin/env node
/**
 * Refresh the official CSL styles embedded in src/csl-styles.generated.ts.
 *
 * Styles come from the CSL project's repository
 * (https://github.com/citation-style-language/styles), licensed CC BY-SA 3.0.
 * They are embedded as strings rather than read from disk at runtime so the
 * package works unchanged inside a bundled server (Vercel, Docker) where a
 * loose .csl file would not be shipped.
 *
 * Usage: node scripts/sync-csl-styles.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const RAW = 'https://raw.githubusercontent.com/citation-style-language/styles/master';

/** Our style id → official CSL file name. */
const STYLES = {
  apa: 'apa',
  mla: 'modern-language-association',
  chicago: 'chicago-author-date',
  harvard: 'harvard-cite-them-right',
  vancouver: 'nlm-citation-sequence',
  ieee: 'ieee',
  ama: 'american-medical-association',
};

const out = [];
for (const [id, file] of Object.entries(STYLES)) {
  const res = await fetch(`${RAW}/${file}.csl`);
  if (!res.ok) throw new Error(`${file}.csl: HTTP ${res.status}`);
  const xml = await res.text();
  if (xml.includes('independent-parent')) throw new Error(`${file}.csl is a dependent style`);
  const title = /<title>([^<]+)<\/title>/.exec(xml)?.[1] ?? file;
  const updated = /<updated>([^<]+)<\/updated>/.exec(xml)?.[1] ?? '';
  out.push({ id, file, title, updated, xml });
  console.log(`${id.padEnd(10)} ${file}.csl  ${title}  (${updated})`);
}

const body = [
  '/* eslint-disable */',
  '// GENERATED by scripts/sync-csl-styles.mjs — do not edit by hand.',
  '// Official CSL styles from https://github.com/citation-style-language/styles,',
  '// licensed under CC BY-SA 3.0 (http://creativecommons.org/licenses/by-sa/3.0/).',
  '',
  'export interface EmbeddedCslStyle {',
  '  /** Official file name in the CSL repository, without `.csl`. */',
  '  file: string;',
  '  title: string;',
  '  updated: string;',
  '  xml: string;',
  '}',
  '',
  'export const CSL_STYLES = {',
  ...out.map(
    (s) =>
      `  ${s.id}: { file: ${JSON.stringify(s.file)}, title: ${JSON.stringify(s.title)}, updated: ${JSON.stringify(s.updated)}, xml: ${JSON.stringify(s.xml)} },`,
  ),
  '} as const satisfies Record<string, EmbeddedCslStyle>;',
  '',
].join('\n');

const target = join(dirname(fileURLToPath(import.meta.url)), '../src/csl-styles.generated.ts');
writeFileSync(target, body);
console.log(`wrote ${target}`);
