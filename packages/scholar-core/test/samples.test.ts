/**
 * Sample outputs committed under docs/samples/scholar-core/ (brief §7, M2).
 *
 * `pnpm samples` writes them. A normal test run regenerates them in memory and
 * fails if a committed file no longer matches, so the samples a reader sees
 * are always what the current code produces.
 *
 * Everything runs offline: references are verified against the recorded
 * responses of the quality test, and the search sample replays the search
 * test's recordings.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { CITATION_STYLES, formatCitations } from '../src/format';
import { svgToPng } from '../src/png';
import { prismaFlowDiagram, type PrismaCounts } from '../src/prisma';
import { searchPapers } from '../src/search';
import { verifyReferences } from '../src/verify';
import { openCassette } from './support/cassette';
import { SEARCH_QUERIES } from './support/search-queries';

const WRITE = process.env.SCHOLAR_WRITE_SAMPLES === '1';
const OUT = join(__dirname, '../../../docs/samples/scholar-core');
const FIXTURES = join(__dirname, 'fixtures');

interface Fixture {
  id: string;
  input: string;
}
const raw = JSON.parse(readFileSync(join(FIXTURES, 'references.json'), 'utf8')) as Fixture[] | { references: Fixture[] };
const fixtures = Array.isArray(raw) ? raw : raw.references;
/** A spread: Vancouver, RIS, a group author, an injected page error, a fabricated and a retracted paper. */
const SAMPLE_IDS = ['correct-01', 'correct-20', 'correct-24', 'injected-12', 'fabricated-01', 'retracted-01'];

const files = new Map<string, string | Uint8Array>();
const emit = (name: string, content: string | Uint8Array) => files.set(name, content);

const PRISMA_DB_ONLY: PrismaCounts = {
  databaseSources: [
    { name: 'MEDLINE (PubMed)', n: 812 },
    { name: 'Embase', n: 1045 },
    { name: 'Cochrane CENTRAL', n: 233 },
  ],
  registers: 41,
  duplicatesRemoved: 498,
  automationIneligible: 0,
  otherRemoved: 12,
  recordsScreened: 1621,
  recordsExcluded: 1450,
  reportsSought: 171,
  reportsNotRetrieved: 6,
  reportsAssessed: 165,
  reportsExcludedReasons: [
    { name: 'Wrong population', n: 61 },
    { name: 'Wrong outcome', n: 38 },
    { name: 'Not a randomised controlled trial', n: 27 },
    { name: 'Duplicate report of an included trial', n: 9 },
  ],
  studiesIncluded: 24,
  reportsIncluded: 30,
};

const PRISMA_WITH_OTHER: PrismaCounts = {
  ...PRISMA_DB_ONLY,
  reportsIncluded: 34,
  otherMethods: {
    websites: 14,
    organisations: 3,
    citationSearching: 27,
    reportsSought: 44,
    reportsNotRetrieved: 2,
    reportsAssessed: 42,
    reportsExcludedReasons: [
      { name: 'Wrong population', n: 30 },
      { name: 'Wrong outcome', n: 8 },
    ],
  },
};

describe('docs/samples/scholar-core', () => {
  it('formats verified references in every style and export format', async () => {
    const cassette = openCassette(join(FIXTURES, 'cassettes'));
    const inputs = SAMPLE_IDS.map((id) => fixtures.find((f) => f.id === id)!.input);
    // Verified one by one, exactly as the quality test does, so the recordings cover them.
    const verified = [];
    for (const [i, text] of inputs.entries()) {
      const [r] = await verifyReferences(text, { http: cassette.http, concurrency: 1 });
      verified.push({ ...r!, index: i });
    }
    const input = inputs.join('\n\n');
    expect(cassette.misses).toEqual([]);
    expect(verified.map((v) => v.status)).toEqual([
      'verified',
      'verified',
      'verified',
      'verified_with_corrections',
      'likely_fabricated',
      'retracted',
    ]);

    const md = [
      '# formatCitations — sample output',
      '',
      'Generated by `pnpm --filter @pho/scholar-core samples` from six references in the',
      'quality fixtures, after `verifyReferences`. Verified entries are formatted from the',
      'matched database record; the fabricated one is formatted as cited and flagged.',
      '',
      '## Input',
      '',
      '```text',
      input,
      '```',
      '',
      '## Verification',
      '',
      '| # | status | summary |',
      '| --- | --- | --- |',
      ...verified.map((v) => `| ${v.index + 1} | ${v.status} | ${v.summary.replace(/\|/g, '\\|')} |`),
    ];
    for (const style of CITATION_STYLES) {
      const r = formatCitations(verified, style, 'text');
      md.push('', `## ${style} — ${r.styleTitle}`, '', '**Bibliography**', '', '```text', r.content, '```', '');
      md.push('**In-text**', '', ...r.entries.map((e) => `- [${e.index + 1}] ${e.inText}`));
      if (r.warnings.length) md.push('', '**Warnings**', '', ...r.warnings.map((w) => `- ${w}`));
    }
    emit('citations.md', `${md.join('\n')}\n`);
    emit('citations-apa.html', `${formatCitations(verified, 'apa', 'html').content}\n`);
    emit('references.bib', `${formatCitations(verified, 'apa', 'bibtex').content}\n`);
    emit('references.ris', `${formatCitations(verified, 'apa', 'ris').content}\n`);
    emit('references.csl.json', `${formatCitations(verified, 'apa', 'csl-json').content}\n`);
  });

  it('searches real databases', async () => {
    const cassette = openCassette(join(FIXTURES, 'cassettes-search'));
    const q = SEARCH_QUERIES[0]!;
    const r = await searchPapers(q.query, q.filters, { http: cassette.http });
    expect(cassette.misses).toEqual([]);
    const { results, ...meta } = r;
    emit('search-sepsis.json', `${JSON.stringify({ ...meta, results: results.map(({ work: _w, ...p }) => p) }, null, 2)}\n`);
    emit(
      'search-sepsis.md',
      [
        `# searchPapers — "${q.query}", ${q.filters.yearFrom}–${q.filters.yearTo}`,
        '',
        '| # | title | year | journal | DOI / PMID | open access | found in |',
        '| --- | --- | --- | --- | --- | --- | --- |',
        ...results.map((p) =>
          [
            '',
            p.rank,
            `${p.title.replace(/\|/g, '\\|')}${p.preprint ? ' *(preprint, not peer reviewed)*' : ''}`,
            p.year ?? '',
            (p.journal ?? '').replace(/\|/g, '\\|'),
            [p.doi && `[${p.doi}](https://doi.org/${p.doi})`, p.pmid && `[PMID ${p.pmid}](https://pubmed.ncbi.nlm.nih.gov/${p.pmid}/)`]
              .filter(Boolean)
              .join('<br>'),
            p.openAccess.isOa ? (p.openAccess.url ? `[yes](${p.openAccess.url})` : 'yes') : 'no',
            p.foundIn.join(', '),
            '',
          ].join(' | ').trim(),
        ),
        '',
        `Excluded: ${JSON.stringify(r.excluded)}`,
        '',
      ].join('\n'),
    );
  });

  it('draws PRISMA 2020 diagrams', () => {
    const dbOnly = prismaFlowDiagram(PRISMA_DB_ONLY);
    const withOther = prismaFlowDiagram(PRISMA_WITH_OTHER);
    expect(dbOnly.warnings).toEqual([]);
    expect(withOther.warnings).toEqual([]);
    emit('prisma-2020-databases.svg', `${dbOnly.svg}\n`);
    emit('prisma-2020-databases.png', svgToPng(dbOnly.svg));
    emit('prisma-2020-with-other-methods.svg', `${withOther.svg}\n`);
    emit('prisma-2020-with-other-methods.png', svgToPng(withOther.svg));
    const wrong = prismaFlowDiagram({ ...PRISMA_DB_ONLY, recordsScreened: 1650, reportsIncluded: 28 });
    emit('prisma-2020-warnings.json', `${JSON.stringify(wrong.warnings, null, 2)}\n`);
  });

  it('matches the committed files', () => {
    if (WRITE) {
      mkdirSync(OUT, { recursive: true });
      for (const [name, content] of files) writeFileSync(join(OUT, name), content);
      return;
    }
    for (const [name, content] of files) {
      const p = join(OUT, name);
      expect(existsSync(p), `${name} missing — run pnpm --filter @pho/scholar-core samples`).toBe(true);
      // PNG bytes depend on the rasteriser build; the SVG next to it is the checked source.
      if (typeof content === 'string') expect(readFileSync(p, 'utf8'), `${name} is stale — run samples`).toBe(content);
    }
  });
});
