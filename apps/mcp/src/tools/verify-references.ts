import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { parseReferences, summarize, verifyReferences, type ParsedRef, type VerificationResult } from '@pho/scholar-core';
import { z } from 'zod';
import { errorResult, quotaExceededText, quotaLine, runTool, takeQuota, type QuotaInfo, type ToolContext } from '../context';
import {
  MAX_REFERENCE_INPUT_CHARS,
  MAX_REFERENCES_PER_CALL,
  STATUS_MARK,
  linksSchema,
  noticeSchema,
  noticesOut,
  quotaSchema,
  truncate,
  workMetadata,
} from './shared';

export const VERIFY_DESCRIPTION = [
  'Check every reference in a list against Crossref, PubMed and OpenAlex and report, for each one, whether the paper really exists and whether the details are right.',
  'Works on lists written by a person or generated by an AI model.',
  'Input: a pasted reference list in any common style (APA, Vancouver, numbered, mixed), BibTeX, RIS, CSL-JSON, or one DOI per line.',
  'Each reference gets exactly one status: verified, verified_with_corrections (real paper, some details wrong; corrected metadata included), likely_fabricated (no such paper exists), not_found (could not be confirmed either way), retracted, or ambiguous (several papers fit).',
  'likely_fabricated, not_found and ambiguous mean the reference could not be confirmed as a real paper; retracted means the paper exists but has been withdrawn.',
  `At most ${MAX_REFERENCES_PER_CALL} references per call.`,
].join(' ');

const referenceOut = z.object({
  index: z.number().int(),
  status: z.enum([
    'verified',
    'verified_with_corrections',
    'likely_fabricated',
    'not_found',
    'retracted',
    'ambiguous',
    'not_checked',
  ]),
  confidence: z.number().optional(),
  summary: z.string(),
  cited: z.string(),
  corrected: z
    .object({
      title: z.string(),
      authors: z.array(z.string()),
      year: z.number().int().optional(),
      journal: z.string().optional(),
      volume: z.string().optional(),
      issue: z.string().optional(),
      pages: z.string().optional(),
      doi: z.string().optional(),
      pmid: z.string().optional(),
    })
    .optional(),
  mismatches: z.array(z.object({ field: z.string(), cited: z.string(), found: z.string() })),
  links: linksSchema,
  retraction: z.object({ status: z.string(), notices: z.array(noticeSchema) }).optional(),
});

export const verifyOutputSchema = {
  summary: z.object({
    total: z.number().int(),
    verified: z.number().int(),
    verified_with_corrections: z.number().int(),
    likely_fabricated: z.number().int(),
    not_found: z.number().int(),
    retracted: z.number().int(),
    ambiguous: z.number().int(),
    not_checked: z.number().int(),
  }),
  references: z.array(referenceOut),
  quota: quotaSchema,
};

const CONFIRMED = new Set(['verified', 'verified_with_corrections', 'retracted']);

export function referenceRow(r: VerificationResult) {
  return {
    index: r.index + 1,
    status: r.status,
    confidence: Math.round(r.confidence * 100) / 100,
    summary: r.summary,
    cited: truncate(r.input.raw, 600),
    // Only a confirmed match is offered as the corrected record; for `ambiguous`
    // the best candidate is one of several and must not read as the answer.
    ...(r.match && CONFIRMED.has(r.status) ? { corrected: workMetadata(r.match) } : {}),
    mismatches: r.mismatches.map((m) => ({ field: m.field, cited: m.cited, found: m.found })),
    links: r.links,
    ...(r.retraction ? { retraction: { status: r.retraction.status, notices: noticesOut(r.retraction) } } : {}),
  };
}

export function notCheckedRow(ref: ParsedRef) {
  return {
    index: ref.index + 1,
    status: 'not_checked' as const,
    summary: 'Not checked: the allowance ran out before this reference.',
    cited: truncate(ref.raw, 600),
    mismatches: [],
    links: {} as { doi?: string; pubmed?: string },
  };
}

/** Parse, cap and verify as many references as the quota allows. */
export async function verifyWithinQuota(
  ctx: ToolContext,
  input: string,
): Promise<
  | { kind: 'empty' }
  | { kind: 'too_many'; count: number }
  | { kind: 'quota'; info: QuotaInfo }
  | { kind: 'ok'; refs: ParsedRef[]; results: VerificationResult[]; unchecked: ParsedRef[]; info: QuotaInfo }
> {
  const refs = parseReferences(input);
  if (refs.length === 0) return { kind: 'empty' };
  if (refs.length > MAX_REFERENCES_PER_CALL) return { kind: 'too_many', count: refs.length };
  const quota = await takeQuota(ctx, 'verifications', refs.length);
  if (quota.granted < 1) return { kind: 'quota', info: quota.info };
  const toCheck = refs.slice(0, quota.granted);
  const results = await verifyReferences(toCheck, {
    http: ctx.http,
    contactEmail: ctx.config.contactEmail,
    pubmedApiKey: ctx.config.pubmedApiKey,
    openalexApiKey: ctx.config.openalexApiKey,
  });
  return { kind: 'ok', refs, results, unchecked: refs.slice(quota.granted), info: quota.info };
}

export function inputProblem(
  ctx: ToolContext,
  v: Exclude<Awaited<ReturnType<typeof verifyWithinQuota>>, { kind: 'ok' }>,
) {
  if (v.kind === 'empty') return errorResult('No references were found in the input. Paste the reference list, BibTeX, RIS or DOIs.');
  if (v.kind === 'too_many')
    return errorResult(
      `The input has ${v.count} references; one call checks at most ${MAX_REFERENCES_PER_CALL}. Split the list and call again for each part.`,
    );
  return errorResult(quotaExceededText(ctx, v.info), { error: 'quota_exceeded', quota: v.info });
}

type Row = ReturnType<typeof referenceRow> | ReturnType<typeof notCheckedRow>;
type Summary = z.infer<typeof verifyOutputSchema.summary>;

function textReport(rows: Row[], s: Summary, info: QuotaInfo) {
  const head =
    `Checked ${s.total - s.not_checked} of ${s.total} references: ${s.verified} verified, ` +
    `${s.verified_with_corrections} real with errors, ${s.likely_fabricated} likely fabricated, ` +
    `${s.not_found} not found, ${s.retracted} retracted, ${s.ambiguous} ambiguous` +
    (s.not_checked ? `, ${s.not_checked} not checked (allowance used up)` : '') +
    '.';
  const lines = rows.map((r) => {
    const links: { doi?: string; pubmed?: string } = r.links;
    const link = links.doi ?? links.pubmed ?? '';
    return `${r.index}. ${STATUS_MARK[r.status] ?? ''} ${r.status}: ${r.summary}${link ? ` ${link}` : ''}`;
  });
  return [head, '', ...lines, '', quotaLine(info)].join('\n');
}

export function registerVerifyReferences(server: McpServer, ctx: ToolContext): void {
  server.registerTool(
    'verify_references',
    {
      title: 'Verify references',
      description: VERIFY_DESCRIPTION,
      inputSchema: {
        references: z
          .string()
          .min(1)
          .max(MAX_REFERENCE_INPUT_CHARS)
          .describe('The reference list exactly as written: any citation style, BibTeX, RIS, CSL-JSON, or DOIs one per line.'),
      },
      outputSchema: verifyOutputSchema,
      annotations: { title: 'Verify references', readOnlyHint: true, destructiveHint: false, openWorldHint: true, idempotentHint: true },
    },
    async ({ references }) =>
      runTool(ctx, 'verify_references', async (track) => {
        const v = await verifyWithinQuota(ctx, references);
        if (v.kind !== 'ok') {
          track({ result_status: v.kind === 'quota' ? 'quota_exceeded' : 'invalid_input' });
          return inputProblem(ctx, v);
        }
        const rows = [...v.results.map(referenceRow), ...v.unchecked.map(notCheckedRow)];
        const summary = { ...summarize(v.results), total: v.refs.length, not_checked: v.unchecked.length };
        track({
          result_status: v.unchecked.length ? 'partial' : 'ok',
          references: summary.total,
          verified: summary.verified,
          corrected: summary.verified_with_corrections,
          fabricated: summary.likely_fabricated,
          not_found: summary.not_found,
          retracted: summary.retracted,
          ambiguous: summary.ambiguous,
          not_checked: summary.not_checked,
        });
        return {
          content: [{ type: 'text', text: textReport(rows, summary, v.info) }],
          structuredContent: { summary, references: rows, quota: v.info },
        };
      }),
  );
}
